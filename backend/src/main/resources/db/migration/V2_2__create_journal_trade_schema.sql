CREATE TABLE IF NOT EXISTS journal_trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL DEFAULT 'default',
    symbol VARCHAR(16) NOT NULL,
    portfolio_id BIGINT,
    transaction_id BIGINT,
    company VARCHAR(128) NOT NULL,
    trade_type VARCHAR(16) NOT NULL,
    quantity NUMERIC(18, 6) NOT NULL,
    purchase_price NUMERIC(18, 6) NOT NULL,
    current_price NUMERIC(18, 6) NOT NULL,
    market_value NUMERIC(18, 6) NOT NULL,
    commission NUMERIC(18, 6) NOT NULL,
    strategy VARCHAR(128),
    notes VARCHAR(1000),
    opened_at DATE NOT NULL,
    closed_at DATE,
    status VARCHAR(16) NOT NULL,
    pnl NUMERIC(18, 6) NOT NULL,
    return_pct NUMERIC(18, 6) NOT NULL,
    holding_days BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_journal_trades_user_opened
    ON journal_trades (user_id, opened_at DESC, id DESC);
