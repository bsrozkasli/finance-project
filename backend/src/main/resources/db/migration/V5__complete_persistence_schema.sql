    ADD COLUMN IF NOT EXISTS gross_profit NUMERIC(26, 4) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS operating_income NUMERIC(26, 4) NOT NULL DEFAULT 0;

ALTER TABLE financial_statements
    ALTER COLUMN gross_profit DROP DEFAULT,
    ALTER COLUMN operating_income DROP DEFAULT;

CREATE TABLE IF NOT EXISTS fundamental_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(20) NOT NULL,
    calculated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    fiscal_year VARCHAR(10),
    roa NUMERIC(19, 4),
    roe NUMERIC(19, 4),
    roic NUMERIC(19, 4),
    current_ratio NUMERIC(19, 4),
    debt_to_equity NUMERIC(19, 4),
    ev_fcf NUMERIC(19, 4),
    piotroski_score INTEGER,
    piotroski_signals_json TEXT
);

CREATE INDEX IF NOT EXISTS idx_fundamental_snapshots_symbol
    ON fundamental_snapshots (symbol, calculated_at DESC);

CREATE TABLE IF NOT EXISTS portfolio_positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL DEFAULT 'default',
    symbol VARCHAR(16) NOT NULL,
    quantity NUMERIC(18, 6) NOT NULL,
    avg_cost_price NUMERIC(18, 6) NOT NULL,
    opened_at DATE,
    notes VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_portfolio_positions_user_created
    ON portfolio_positions (user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS journal_trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL DEFAULT 'default',
    symbol VARCHAR(16) NOT NULL,
    portfolio_id BIGINT,
    transaction_id BIGINT,
    company VARCHAR(128) NOT NULL,
    trade_type VARCHAR(16) NOT NULL,
    quantity NUMERIC(18, 6) NOT NULL,
    purchase_price NUMERIC(18, 6) NOT NULL,
    current_price NUMERIC(18, 6) NOT NULL,
    market_value NUMERIC(18, 6) NOT NULL,
    commission NUMERIC(18, 6) NOT NULL,
    strategy VARCHAR(128),
    notes VARCHAR(1000),
    opened_at DATE NOT NULL,
    closed_at DATE,
    status VARCHAR(16) NOT NULL,
    pnl NUMERIC(18, 6) NOT NULL,
    return_pct NUMERIC(18, 6) NOT NULL,
    holding_days BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_journal_trades_user_opened
    ON journal_trades (user_id, opened_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_journal_trades_portfolio_id
    ON journal_trades (portfolio_id);

CREATE INDEX IF NOT EXISTS idx_journal_trades_transaction_id
    ON journal_trades (transaction_id);

CREATE TABLE IF NOT EXISTS journal_trade_tags (
    trade_id BIGINT NOT NULL,
    tag_order INTEGER NOT NULL,
    tag VARCHAR(64) NOT NULL,
    PRIMARY KEY (trade_id, tag_order),
    CONSTRAINT fk_journal_trade_tags_trade
        FOREIGN KEY (trade_id) REFERENCES journal_trades(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS watchlists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL DEFAULT 'default',
    name VARCHAR(128) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_watchlists_user_id
    ON watchlists (user_id, id);

CREATE TABLE IF NOT EXISTS watchlist_symbols (
    watchlist_id BIGINT NOT NULL,
    symbol_order INTEGER NOT NULL,
    symbol VARCHAR(16) NOT NULL,
    PRIMARY KEY (watchlist_id, symbol_order),
    CONSTRAINT fk_watchlist_symbols_watchlist
        FOREIGN KEY (watchlist_id) REFERENCES watchlists(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS opportunity_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(20) NOT NULL,
    score INTEGER NOT NULL,
    message VARCHAR(500) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    is_read BOOLEAN NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_opportunity_notifications_unread
    ON opportunity_notifications (is_read, created_at DESC);
